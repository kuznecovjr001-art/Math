"""
Числа в словах с правильным падежом и родом для синтеза речи.

Синтезатор плохо угадывает форму числительного («в 6 коробках», «до 100», «1 единица»), поэтому фраза
приходит к нему уже со словами: «в шести коробках», «до ста», «одна единица».

Падеж числа: предлог перед ним («до/от/из» — родительный, «в» без существительного — предложный),
«не хватает» — родительный, иначе падеж следующего существительного во множественном числе
(«в 6 коробках» — предложный). Род для 1 и 2 — по следующему существительному, без него — по последнему
посчитанному предмету во фразе («В первом 1» после «рыбок» — «одна»).

Запуск самопроверки: python tts/normalize_ru.py
"""
import re

import pymorphy3

MORPH = pymorphy3.MorphAnalyzer()

CASES = ['nomn', 'gent', 'datv', 'accs', 'ablt', 'loct']

UNITS = {
    1: {'m': ['один', 'одного', 'одному', 'один', 'одним', 'одном'],
        'f': ['одна', 'одной', 'одной', 'одну', 'одной', 'одной'],
        'n': ['одно', 'одного', 'одному', 'одно', 'одним', 'одном']},
    2: {'m': ['два', 'двух', 'двум', 'два', 'двумя', 'двух'],
        'f': ['две', 'двух', 'двум', 'две', 'двумя', 'двух']},
    3: ['три', 'трёх', 'трём', 'три', 'тремя', 'трёх'],
    4: ['четыре', 'четырёх', 'четырём', 'четыре', 'четырьмя', 'четырёх'],
}


def _five_like(nom, stem):
    # пять, пяти, пяти, пять, пятью, пяти
    return [nom, stem + 'и', stem + 'и', nom, stem + 'ью', stem + 'и']


for n, (nom, stem) in {5: ('пять', 'пят'), 6: ('шесть', 'шест'), 7: ('семь', 'сем'), 8: ('восемь', 'восьм'),
                       9: ('девять', 'девят'), 10: ('десять', 'десят'), 11: ('одиннадцать', 'одиннадцат'),
                       12: ('двенадцать', 'двенадцат'), 13: ('тринадцать', 'тринадцат'),
                       14: ('четырнадцать', 'четырнадцат'), 15: ('пятнадцать', 'пятнадцат'),
                       16: ('шестнадцать', 'шестнадцат'), 17: ('семнадцать', 'семнадцат'),
                       18: ('восемнадцать', 'восемнадцат'), 19: ('девятнадцать', 'девятнадцат'),
                       20: ('двадцать', 'двадцат'), 30: ('тридцать', 'тридцат')}.items():
    UNITS[n] = _five_like(nom, stem)
UNITS[8][4] = 'восемью'
UNITS[0] = ['ноль', 'ноля', 'нолю', 'ноль', 'нолём', 'ноле']
UNITS[40] = ['сорок', 'сорока', 'сорока', 'сорок', 'сорока', 'сорока']
UNITS[90] = ['девяносто', 'девяноста', 'девяноста', 'девяносто', 'девяноста', 'девяноста']
UNITS[100] = ['сто', 'ста', 'ста', 'сто', 'ста', 'ста']
for n, a, b in [(50, 'пять', 'пяти'), (60, 'шесть', 'шести'), (70, 'семь', 'семи'), (80, 'восемь', 'восьми')]:
    UNITS[n] = [a + 'десят', b + 'десяти', b + 'десяти', a + 'десят', b + 'юдесятью' if n != 80 else 'восемьюдесятью', b + 'десяти']
UNITS[50][4], UNITS[60][4], UNITS[70][4] = 'пятьюдесятью', 'шестьюдесятью', 'семьюдесятью'
HUNDREDS = {
    200: ['двести', 'двухсот', 'двумстам', 'двести', 'двумястами', 'двухстах'],
    300: ['триста', 'трёхсот', 'трёмстам', 'триста', 'тремястами', 'трёхстах'],
    400: ['четыреста', 'четырёхсот', 'четырёмстам', 'четыреста', 'четырьмястами', 'четырёхстах'],
}
for n, (a, g, d, i, l) in {500: ('пятьсот', 'пятисот', 'пятистам', 'пятьюстами', 'пятистах'),
                           600: ('шестьсот', 'шестисот', 'шестистам', 'шестьюстами', 'шестистах'),
                           700: ('семьсот', 'семисот', 'семистам', 'семьюстами', 'семистах'),
                           800: ('восемьсот', 'восьмисот', 'восьмистам', 'восемьюстами', 'восьмистах'),
                           900: ('девятьсот', 'девятисот', 'девятистам', 'девятьюстами', 'девятистах')}.items():
    HUNDREDS[n] = [a, g, d, a, i, l]
HUNDREDS[100] = UNITS[100]
THOUSAND = ['тысяча', 'тысячи', 'тысяче', 'тысячу', 'тысячей', 'тысяче']


def _part(n, case, gender):
    forms = UNITS[n]
    if isinstance(forms, dict):
        forms = forms.get(gender) or forms['m']
    return forms[CASES.index(case)]


def number_words(n: int, case: str = 'nomn', gender: str = 'm') -> str:
    """Составное числительное: склоняются все части («двадцати пяти»)."""
    if n == 1000:
        return 'одна ' + THOUSAND[CASES.index(case)] if case != 'nomn' else 'тысяча'
    if n == 0:
        return _part(0, case, gender)
    words = []
    if n >= 100:
        words.append(HUNDREDS[n // 100 * 100][CASES.index(case)])
        n %= 100
    if n >= 20:
        words.append(_part(n // 10 * 10, case, gender))
        n %= 10
    if n:
        words.append(_part(n, case, gender))
    return ' '.join(words)


PREP_CASE = {'до': 'gent', 'от': 'gent', 'из': 'gent', 'без': 'gent', 'около': 'gent', 'после': 'gent',
             'для': 'gent', 'у': 'gent', 'к': 'datv', 'с': 'ablt', 'между': 'ablt', 'в': 'loct'}
GENDER = {'masc': 'm', 'femn': 'f', 'neut': 'n'}
TOKEN = re.compile(r'\d+|[А-Яа-яЁё]+|[^\sА-Яа-яЁё\d]+|\s+')


def _noun(word):
    # После числа существительное чаще в родительном («2 десятка» — десяток, а не «десятка»): такой разбор первым.
    nouns = [p for p in MORPH.parse(word) if p.tag.POS == 'NOUN']
    return next((p for p in nouns if p.tag.case == 'gent'), nouns[0] if nouns else None)


def _next_noun(tokens, i):
    """Существительное сразу после числа (через прилагательное: «# красных тюльпанов»)."""
    words = [t for t in tokens[i + 1:i + 6] if t.strip()]
    for w in words[:2]:
        if not re.match(r'[А-Яа-яЁё]+$', w):
            return None
        p = _noun(w)
        if p and not MORPH.parse(w)[0].tag.POS in ('ADJF', 'PRTF'):
            return p
    return None


def normalize(text: str) -> str:
    tokens = TOKEN.findall(text)
    out, last_gender = [], 'm'
    for i, t in enumerate(tokens):
        if not t.isdigit():
            if re.match(r'[А-Яа-яЁё]+$', t):
                p = _noun(t)
                if p and p.tag.number == 'plur' and p.tag.case == 'gent' and t.lower() not in ('раз', 'единиц'):
                    last_gender = GENDER.get(p.normalized.tag.gender, last_gender)
            out.append(t)
            continue
        n = int(t)
        prev = [w.lower() for w in tokens[max(0, i - 4):i] if w.strip()]
        prep = prev[-1] if prev else ''
        noun = _next_noun(tokens, i)
        case = 'nomn'
        if prev[-2:] == ['не', 'хватает'] or prep == 'хватает':
            case = 'gent'
        elif prep == 'на' and text.startswith('Длинная'):
            # Подсказка про часы: «длинная (стрелка) на двенадцати».
            case = 'loct'
        elif prep in PREP_CASE:
            case = PREP_CASE[prep]
            # «в 1 коробке»: форма на -е бывает и дательным, и предложным — смотрим все разборы.
            if prep == 'в' and noun is not None and not any(p.tag.case == 'loct' for p in MORPH.parse(noun.word) if p.tag.POS == 'NOUN'):
                case = 'accs'
        elif noun is not None and noun.tag.number == 'plur' and noun.tag.case in ('datv', 'ablt', 'loct'):
            case = noun.tag.case
        if prep == 'по' and n == 1:
            case = 'datv'
        # У форм множественного числа рода нет — берём его у начальной формы («2 ягоды» → «ягода», ж. р.).
        noun_gender = noun.normalized.tag.gender if noun is not None else None
        gender = GENDER.get(noun_gender, last_gender) if noun_gender else last_gender
        if noun_gender:
            last_gender = gender
        out.append(number_words(n, case, gender))
    return ''.join(out)


